/**
 * The JSON schemas of the Teams / Microsoft 365 app manifest, bundled into the tool as data (feature 008).
 *
 *   node scripts/gen-schemas.mjs <folder with vX.Y.json files> [YYYY-MM-DD]
 *
 * The tool never downloads anything (Principle II). A developer downloads the schemas once, for example
 *   curl -o v1.24.json https://developer.microsoft.com/en-us/json-schemas/teams/v1.24/MicrosoftTeams.schema.json
 * and runs this script. A file that is not a schema (a 404 page) is skipped and said so. For each version it writes
 * `src/schemas/teams-vX.Y.json` (minified, each `description` cut to its first sentence of at most 160 characters,
 * plus `x-source` and `x-read`) and then `src/schemas/index.ts`, which lists them.
 */

import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'schemas');
const from = process.argv[2];
const read = process.argv[3] ?? new Date().toISOString().slice(0, 10);
if (!from) { console.error('usage: node scripts/gen-schemas.mjs <folder> [YYYY-MM-DD]'); process.exit(1); }

const first = (text) => (text.split(/(?<=[.!?])\s/)[0] ?? '').slice(0, 160);
const shorten = (n) => {
    if (Array.isArray(n)) return n.map(shorten);
    if (n && typeof n === 'object') {
        return Object.fromEntries(Object.entries(n).map(([k, v]) => [k, k === 'description' && typeof v === 'string' ? first(v) : shorten(v)]));
    }
    return n;
};

mkdirSync(out, { recursive: true });
for (const f of readdirSync(out)) if (/^teams-v.*\.json$/.test(f)) rmSync(join(out, f));

const versions = [];
for (const name of readdirSync(from)) {
    const m = /^v(\d+\.\d+)\.json$/.exec(name);
    if (!m) continue;
    let schema;
    try { schema = JSON.parse(readFileSync(join(from, name), 'utf8')); } catch { schema = null; }
    if (!schema || typeof schema !== 'object' || !schema.properties || !schema.properties.manifestVersion) { console.log(`skipped ${name}: not a manifest schema`); continue; }
    const version = m[1];
    const body = { ...shorten(schema), 'x-source': `https://developer.microsoft.com/en-us/json-schemas/teams/v${version}/MicrosoftTeams.schema.json`, 'x-read': read };
    writeFileSync(join(out, `teams-v${version}.json`), JSON.stringify(body));
    versions.push(version);
}
versions.sort((a, b) => { const [a1, a2] = a.split('.').map(Number); const [b1, b2] = b.split('.').map(Number); return a1 - b1 || a2 - b2; });

const id = (v) => `v${v.replace('.', '_')}`;
const index = `/** Generated by scripts/gen-schemas.mjs on ${read}. Do not edit. */

${versions.map(v => `import ${id(v)} from './teams-v${v}.json';`).join('\n')}

export const SCHEMAS: Readonly<Record<string, object>> = {
${versions.map(v => `    '${v}': ${id(v)},`).join('\n')}
};

export const SCHEMA_READ = '${read}';
`;
writeFileSync(join(out, 'index.ts'), index);
console.log(`${versions.length} schemas: ${versions.join(', ')}`);
